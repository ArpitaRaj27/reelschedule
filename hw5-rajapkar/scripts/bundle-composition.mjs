// HW5 Task 6: which code makes up the largest JavaScript asset? No packages needed.
//
//   node hw5-rajapkar/scripts/bundle-composition.mjs web/dist/assets/index-XXXX.js
//
// Needs the asset's source map next to it. Production no longer ships one (Task 6 decision), so build
// locally with a map the JS does not link to: npm run build -w web -- --sourcemap hidden
//
// Reads the asset and its source map (<asset>.map), decodes the map's "mappings" (base64 VLQ) and
// credits every byte of the minified file to the original source it came from, then groups the
// sources by npm package (node_modules/<name> or node_modules/@scope/<name>) or "app code (web/src)".
// Bytes that no mapping covers (Rollup's glue between modules) are listed as "unmapped".
// The numbers are minified, uncompressed bytes; compression shrinks every group, not equally.
import { readFileSync } from "node:fs";
import path from "node:path";

const asset = process.argv[2];
if (!asset) {
  console.error("usage: node bundle-composition.mjs <path to .js asset>");
  process.exit(1);
}
const code = readFileSync(asset, "utf8");
const map = JSON.parse(readFileSync(`${asset}.map`, "utf8"));

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const val = Object.fromEntries([...B64].map((c, i) => [c, i]));
function decodeSegment(seg) {
  const out = [];
  let shift = 0;
  let value = 0;
  for (const ch of seg) {
    const d = val[ch];
    value += (d & 31) << shift;
    if (d & 32) shift += 5;
    else {
      out.push(value & 1 ? -(value >>> 1) : value >>> 1);
      shift = 0;
      value = 0;
    }
  }
  return out;
}

function groupOf(source) {
  const s = source.replace(/\\/g, "/");
  const nm = s.lastIndexOf("node_modules/");
  if (nm >= 0) {
    const rest = s.slice(nm + "node_modules/".length).split("/");
    return rest[0].startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0];
  }
  if (s.includes("/src/") || s.startsWith("src/") || s.includes("web/src")) return "app code (web/src)";
  return `other: ${path.basename(s)}`;
}

const lines = code.split("\n");
const mapLines = map.mappings.split(";");
const bytes = new Map();
let sourceIndex = 0;
let mapped = 0;
for (let li = 0; li < lines.length; li++) {
  const line = lines[li];
  const segs = (mapLines[li] ?? "").split(",").filter(Boolean);
  let genCol = 0;
  const points = []; // [generatedColumn, sourceIndex | -1]
  for (const seg of segs) {
    const f = decodeSegment(seg);
    genCol += f[0];
    if (f.length >= 4) {
      sourceIndex += f[1];
      points.push([genCol, sourceIndex]);
    } else points.push([genCol, -1]);
    // f[2] (line) and f[3] (column) deltas are not needed to attribute generated bytes; names (f[4]) neither.
  }
  for (let p = 0; p < points.length; p++) {
    const [start, src] = points[p];
    const end = p + 1 < points.length ? points[p + 1][0] : line.length;
    if (src < 0 || end <= start) continue;
    const g = groupOf(map.sources[src]);
    // Columns are UTF-16 units; for this ASCII-heavy output that equals bytes closely enough for shares.
    bytes.set(g, (bytes.get(g) ?? 0) + (end - start));
    mapped += end - start;
  }
}
const total = Buffer.byteLength(code, "utf8");
bytes.set("unmapped (bundler glue, comments)", Math.max(0, total - mapped));

const rows = [...bytes.entries()].sort((a, b) => b[1] - a[1]);
console.log(`# ${path.basename(asset)}: ${total.toLocaleString("en-US")} bytes minified, ${map.sources.length} source files`);
console.log("| Package / code | Bytes (minified) | Share |");
console.log("|---|---:|---:|");
for (const [g, b] of rows) console.log(`| ${g} | ${b.toLocaleString("en-US")} | ${((100 * b) / total).toFixed(1)}% |`);
